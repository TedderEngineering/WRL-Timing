/**
 * The hand-written migration for Race Analysis Packages must match
 * schema.prisma exactly (CI runs `prisma migrate diff --exit-code`) and must
 * be additive only. Prisma cannot run in every environment, so this parses
 * both files.
 */
import { describe, expect, it } from "vitest";
import fs from "node:fs";

const read = (rel: string) => fs.readFileSync(new URL(rel, import.meta.url), "utf8");
const SCHEMA = read("../../../prisma/schema.prisma");
const MIGRATION_DIR = "20261013000000_race_analysis_packages";
const SQL = read(`../../../prisma/migrations/${MIGRATION_DIR}/migration.sql`);
const SQL_CODE = SQL.split("\n")
  .filter((l) => !l.trim().startsWith("--"))
  .join("\n");

interface Field {
  name: string;
  column: string;
  type: string;
  optional: boolean;
  attrs: string;
}

function block(kind: "model" | "enum", name: string): string {
  const m = SCHEMA.match(new RegExp(`^${kind} ${name} \\{([\\s\\S]*?)^\\}`, "m"));
  if (!m) throw new Error(`${kind} ${name} not found in schema.prisma`);
  return m[1];
}

const ENUMS = [...SCHEMA.matchAll(/^enum (\w+) \{/gm)].map((m) => m[1]);
const MODELS = [...SCHEMA.matchAll(/^model (\w+) \{/gm)].map((m) => m[1]);

/** Scalar (column-backed) fields of a model; relation fields are skipped. */
function scalarFields(model: string): Field[] {
  const out: Field[] = [];
  for (const raw of block("model", model).split("\n")) {
    const line = raw.replace(/\/\/.*$/, "").trim();
    const m = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
    if (!m || line.startsWith("@@")) continue;
    const [, name, type, list, opt, attrs] = m;
    if (list || MODELS.includes(type)) continue; // relation
    const map = attrs.match(/@map\("([^"]+)"\)/);
    out.push({ name, column: map ? map[1] : name, type, optional: !!opt, attrs });
  }
  return out;
}

function sqlType(f: Field): string {
  const base: Record<string, string> = {
    String: "TEXT",
    Int: "INTEGER",
    Boolean: "BOOLEAN",
    DateTime: "TIMESTAMP(3)",
    Json: "JSONB",
    Float: "DOUBLE PRECISION",
    BigInt: "BIGINT",
  };
  if (base[f.type]) return base[f.type];
  if (ENUMS.includes(f.type)) return `"${f.type}"`;
  throw new Error(`No SQL type mapping for ${f.type}`);
}

/** Column definitions of `CREATE TABLE "<table>"`, keyed by column name. */
function createTableColumns(table: string): Map<string, string> {
  const m = SQL_CODE.match(new RegExp(`CREATE TABLE "${table}" \\(([\\s\\S]*?)\\n\\);`));
  if (!m) throw new Error(`CREATE TABLE "${table}" not found in migration`);
  const cols = new Map<string, string>();
  for (const line of m[1].split("\n")) {
    const c = line.trim().match(/^"([^"]+)"\s+(.*?),?$/);
    if (c) cols.set(c[1], c[2]);
  }
  return cols;
}

function expectedDefinition(f: Field): string {
  let def = sqlType(f);
  if (!f.optional) def += " NOT NULL";
  const dflt = f.attrs.match(/@default\(([^)]*\)?)\)/);
  if (dflt) {
    const v = dflt[1];
    if (v === "now()") def += " DEFAULT CURRENT_TIMESTAMP";
    else if (v === "cuid()") def += ""; // generated by Prisma, not the database
    else if (v === "true" || v === "false" || /^\d+$/.test(v)) def += ` DEFAULT ${v}`;
    else def += ` DEFAULT '${v}'`;
  }
  return def;
}

describe(`migration ${MIGRATION_DIR}`, () => {
  it("creates every column of RaceAnalysisPackage with the schema's type, nullability and default", () => {
    const fields = scalarFields("RaceAnalysisPackage");
    expect(fields.map((f) => f.name)).toEqual([
      "id",
      "raceId",
      "version",
      "schemaVersion",
      "engineVersion",
      "rulebookVersion",
      "status",
      "storagePath",
      "sha256",
      "sizeBytes",
      "validatorReport",
      "dataQualityGrade",
      "resultsStatus",
      "createdById",
      "publishedById",
      "createdAt",
      "publishedAt",
      "notes",
    ]);
    const cols = createTableColumns("race_analysis_packages");
    for (const f of fields) {
      expect(cols.get(f.column), `column ${f.column} (${f.name})`).toBe(expectedDefinition(f));
    }
    // and nothing extra
    expect([...cols.keys()].sort()).toEqual(fields.map((f) => f.column).sort());
    expect(SQL_CODE).toContain(`CONSTRAINT "race_analysis_packages_pkey" PRIMARY KEY ("id")`);
  });

  it("adds Race.currentPackageId and Race.packagesDisabled", () => {
    const race = scalarFields("Race");
    const current = race.find((f) => f.name === "currentPackageId")!;
    const disabled = race.find((f) => f.name === "packagesDisabled")!;
    expect(current).toBeDefined();
    expect(disabled).toBeDefined();
    expect(SQL_CODE).toContain(`ADD COLUMN     "${current.column}" ${expectedDefinition(current)}`);
    expect(SQL_CODE).toContain(`ADD COLUMN     "${disabled.column}" ${expectedDefinition(disabled)}`);
  });

  it("creates the enums with the schema's values", () => {
    for (const name of ["RacePackageStatus", "ResultsStatus"]) {
      const values = block("enum", name)
        .split("\n")
        .map((l) => l.replace(/\/\/.*$/, "").trim())
        .filter(Boolean);
      expect(SQL_CODE).toContain(`CREATE TYPE "${name}" AS ENUM (${values.map((v) => `'${v}'`).join(", ")});`);
    }
  });

  it("creates the indexes and foreign keys Prisma expects", () => {
    for (const stmt of [
      `CREATE UNIQUE INDEX "race_analysis_packages_race_id_version_key" ON "race_analysis_packages"("race_id", "version");`,
      `CREATE INDEX "race_analysis_packages_race_id_status_idx" ON "race_analysis_packages"("race_id", "status");`,
      `CREATE INDEX "race_analysis_packages_created_by_id_idx" ON "race_analysis_packages"("created_by_id");`,
      `CREATE INDEX "race_analysis_packages_published_by_id_idx" ON "race_analysis_packages"("published_by_id");`,
      `CREATE UNIQUE INDEX "races_current_package_id_key" ON "races"("current_package_id");`,
      `ALTER TABLE "races" ADD CONSTRAINT "races_current_package_id_fkey" FOREIGN KEY ("current_package_id") REFERENCES "race_analysis_packages"("id") ON DELETE SET NULL ON UPDATE CASCADE;`,
      `ALTER TABLE "race_analysis_packages" ADD CONSTRAINT "race_analysis_packages_race_id_fkey" FOREIGN KEY ("race_id") REFERENCES "races"("id") ON DELETE CASCADE ON UPDATE CASCADE;`,
      `ALTER TABLE "race_analysis_packages" ADD CONSTRAINT "race_analysis_packages_created_by_id_fkey" FOREIGN KEY ("created_by_id") REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE;`,
      `ALTER TABLE "race_analysis_packages" ADD CONSTRAINT "race_analysis_packages_published_by_id_fkey" FOREIGN KEY ("published_by_id") REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE;`,
    ]) {
      expect(SQL_CODE).toContain(stmt);
    }
    expect(block("model", "RaceAnalysisPackage")).toContain("@@unique([raceId, version])");
    expect(block("model", "RaceAnalysisPackage")).toContain('@@map("race_analysis_packages")');
  });

  it("is additive only: no drops, rewrites or data changes", () => {
    const statements = SQL_CODE.replace(/ON (DELETE|UPDATE) (CASCADE|SET NULL|RESTRICT|NO ACTION)/g, "");
    expect(statements).not.toMatch(/\b(DROP|DELETE|UPDATE|TRUNCATE|RENAME)\b/i);
    expect(statements).not.toMatch(/ALTER COLUMN|\bINSERT\b/i);
  });

  it("sorts after every migration that existed before RaceTrace 2.0", () => {
    const dirs = fs
      .readdirSync(new URL("../../../prisma/migrations/", import.meta.url))
      .filter((d) => /^\d/.test(d))
      .sort();
    // Stage 3 migrations (G4 intake, ...) may follow it; nothing older than it may.
    const before = dirs.slice(0, dirs.indexOf(MIGRATION_DIR));
    expect(dirs).toContain(MIGRATION_DIR);
    expect(before.every((d) => d < "20261013000000")).toBe(true);
    expect(dirs.indexOf("20261013000100_add_intake_source_key_api_tokens")).toBeGreaterThan(dirs.indexOf(MIGRATION_DIR));
  });
});
